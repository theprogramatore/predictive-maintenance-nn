from __future__ import annotations

import streamlit as st

from src.inference.predictor import PredictiveMaintenancePredictor


# --------------------------------------------------
# Page configuration
# --------------------------------------------------

st.set_page_config(
    page_title="Predictive Maintenance",
    page_icon="⚙️",
    layout="centered",
)


# --------------------------------------------------
# Load predictor
# --------------------------------------------------

@st.cache_resource
def load_predictor() -> PredictiveMaintenancePredictor:
    """
    Load the trained model only once.
    """
    return PredictiveMaintenancePredictor()


try:
    predictor = load_predictor()

except Exception as exc:
    st.error(
        "The predictive maintenance model "
        "could not be loaded."
    )

    st.exception(exc)
    st.stop()


# --------------------------------------------------
# Header
# --------------------------------------------------

st.title("⚙️ Predictive Maintenance System")

st.write(
    "Neural-network application for estimating "
    "the probability of machine failure."
)

st.divider()


# --------------------------------------------------
# Machine input form
# --------------------------------------------------

st.subheader("Machine Operating Data")

with st.form("machine_form"):

    machine_type = st.selectbox(
        "Product Type",
        options=["L", "M", "H"],
        index=1,
        help=(
            "Machine product quality category: "
            "L = Low, M = Medium, H = High."
        ),
    )

    col1, col2 = st.columns(2)

    with col1:

        air_temperature = st.number_input(
            "Air Temperature (K)",
            min_value=250.0,
            max_value=400.0,
            value=298.1,
            step=0.1,
        )

        rotational_speed = st.number_input(
            "Rotational Speed (rpm)",
            min_value=0,
            max_value=5000,
            value=1551,
            step=1,
        )

        tool_wear = st.number_input(
            "Tool Wear (min)",
            min_value=0,
            max_value=500,
            value=0,
            step=1,
        )

    with col2:

        process_temperature = st.number_input(
            "Process Temperature (K)",
            min_value=250.0,
            max_value=500.0,
            value=308.6,
            step=0.1,
        )

        torque = st.number_input(
            "Torque (Nm)",
            min_value=0.0,
            max_value=200.0,
            value=42.8,
            step=0.1,
        )

    submitted = st.form_submit_button(
        "Analyze Machine",
        use_container_width=True,
    )


# --------------------------------------------------
# Prediction
# --------------------------------------------------

if submitted:

    machine_data = {
        "Air temperature": air_temperature,
        "Process temperature": process_temperature,
        "Rotational speed": rotational_speed,
        "Torque": torque,
        "Tool wear": tool_wear,
        "Type": machine_type,
    }

    try:
        result = predictor.predict(machine_data)

        probability = result["probability"]
        probability_percent = result[
            "probability_percent"
        ]
        threshold = result["threshold"]
        status = result["status"]

        st.divider()

        st.subheader("Prediction Result")

        metric_col1, metric_col2 = st.columns(2)

        with metric_col1:
            st.metric(
                "Failure Probability",
                f"{probability_percent:.2f}%",
            )

        with metric_col2:
            st.metric(
                "Decision Threshold",
                f"{threshold * 100:.0f}%",
            )

        st.progress(
            int(
                max(
                    0,
                    min(
                        100,
                        probability_percent,
                    ),
                )
            )
        )

        if status == "FAILURE WARNING":

            st.error(
                "⚠️ FAILURE WARNING"
            )

            st.write(
                "The neural network estimates that "
                "the machine is above the configured "
                "failure-risk threshold."
            )

        else:

            st.success(
                "✅ MACHINE STATUS: NORMAL"
            )

            st.write(
                "The estimated failure probability "
                "is below the configured threshold."
            )

        st.caption(
            "This prediction is generated by the "
            "trained neural network using the machine "
            "operating conditions entered above."
        )

    except ValueError as exc:
        st.warning(str(exc))

    except Exception as exc:
        st.error(
            "An unexpected prediction error occurred."
        )
        st.exception(exc)


# --------------------------------------------------
# System information
# --------------------------------------------------

st.divider()

with st.expander("How does the system work?"):

    st.markdown(
        """
        **Prediction pipeline**

        1. The operator enters the machine operating data.
        2. The preprocessing pipeline standardizes numeric variables.
        3. Product Type is converted using one-hot encoding.
        4. The neural network receives the processed inputs.
        5. The network generates a probability of machine failure.
        6. The probability is compared with the selected threshold.
        7. The application reports **NORMAL** or
           **FAILURE WARNING**.
        """
    )

st.caption(
    "Predictive Maintenance Neural Network — Educational Project"
)